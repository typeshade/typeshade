// ═══ The JavaScript form of the libm, baked from its source (change 0042, milestone 1a) ═══
//
// The libm is written in `"use typeshade"` (decision N14), one source for each family of
// functions: `src/core/libm/<family>.shade.ts`. The CPU tier calls its JavaScript form, and a
// host page may forbid `new Function`, so the form is generated here and committed:
//
//   src/core/libm/<family>.generated.ts   the factory that `generateModuleJs` writes for the
//                                         source's module in `'f32'` precision, as one
//                                         exported function. Checked by no type
//                                         (`@ts-nocheck`), as the generated module of a host
//                                         face is checked by none.
//
// `bun scripts/bake-libm.ts` writes the files. `--check` writes nothing and fails when one is
// missing or stale; `src/core/libm/libm.test.ts` holds the same.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileLibmSource } from '../src/compiler/ts/libm-source.js';
import { generateModuleJs } from '../src/core/cpu-codegen.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The families of the libm: each is one source and one baked file under `src/core/libm/`,
 *  `<family>.shade.ts` and `<family>.generated.ts`, which exports `<family>Factory`. */
export const LIBM_FAMILIES = ['trig', 'explog'] as const;
export type LibmFamily = (typeof LIBM_FAMILIES)[number];
export const libmSource = (family: LibmFamily): string => `src/core/libm/${family}.shade.ts`;
export const libmGenerated = (family: LibmFamily): string => `src/core/libm/${family}.generated.ts`;

/** The notice of fdlibm, which every baked file carries: the routines derive from fdlibm, and
 *  its licence asks that the notice is preserved (the owner's decision of 2026-11-10; `NOTICE`
 *  at the repository's root carries it too). */
export const FDLIBM_NOTICE =
  `//\n` +
  `// The routines derive from fdlibm. Its notice:\n` +
  `//\n` +
  `//   Copyright (C) 1993 by Sun Microsystems, Inc. All rights reserved.\n` +
  `//   Developed at SunSoft, a Sun Microsystems, Inc. business.\n` +
  `//   Permission to use, copy, modify, and distribute this software is freely granted,\n` +
  `//   provided that this notice is preserved.\n` +
  `//\n`;

/** The members of the factory's `$` that the generated code may read: what `LibmHost` of
 *  `src/core/libm/index.ts` holds, and `F`, which `makeLibm` fills. */
const HOST_MEMBERS: ReadonlySet<string> = new Set(['B', 'L', 'F', 'intDiv', 'intRem']);

/** The baked file's text for the source `text` of the family `family`. Pure. */
export function bakeLibm(text: string, family: LibmFamily): string {
  const LIBM_SOURCE = libmSource(family);
  const compiled = compileLibmSource(text, LIBM_SOURCE);
  const errors = compiled.diagnostics.filter((d) => d.category === 'error');
  if (errors.length > 0) {
    throw new Error(
      `${LIBM_SOURCE} does not compile:\n` +
        errors.map((d) => `  ${d.code} line ${String(d.line)}: ${d.message}`).join('\n'),
    );
  }
  const generated = generateModuleJs(compiled.module, { precision: 'f32' });
  if (generated.fallbacks.length > 0) {
    throw new Error(
      `${LIBM_SOURCE}: no JavaScript was generated for ${generated.fallbacks.join(', ')}`,
    );
  }
  // A member the host does not hold would be `undefined` at the first call, so it fails here.
  for (const m of generated.factorySource.matchAll(/\$\.([A-Za-z_]\w*)/g)) {
    if (!HOST_MEMBERS.has(m[1]!)) {
      throw new Error(`${LIBM_SOURCE}: the generated code reads $.${m[1]!}, which LibmHost lacks`);
    }
  }
  return (
    `// Generated by scripts/bake-libm.ts from ${LIBM_SOURCE}. Do not edit; run \`bun run bake:libm\`.\n` +
    FDLIBM_NOTICE +
    `// @ts-nocheck\n` +
    `export function ${family}Factory($) {\n${generated.factorySource}\n}\n`
  );
}

if (import.meta.main) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const family of LIBM_FAMILIES) {
    const text = bakeLibm(readFileSync(join(ROOT, libmSource(family)), 'utf8'), family);
    const path = join(ROOT, libmGenerated(family));
    if (!check) {
      writeFileSync(path, text);
      console.log(`wrote ${libmGenerated(family)}`);
    } else if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
      console.error(`${libmGenerated(family)} is missing or stale. Run \`bun run bake:libm\`.`);
      stale = true;
    } else {
      console.log(`${libmGenerated(family)} is current.`);
    }
  }
  if (stale) process.exit(1);
}
