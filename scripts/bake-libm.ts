// ═══ The JavaScript form of the libm, baked from its source (change 0042, milestone 1a) ═══
//
// The libm is one `"use typeshade"` source (decision N14): `src/core/libm/trig.shade.ts`. The
// CPU tier calls its JavaScript form, and a host page may forbid `new Function`, so the form is
// generated here and committed:
//
//   src/core/libm/trig.generated.ts   the factory that `generateModuleJs` writes for the
//                                     source's module in `'f32'` precision, as one exported
//                                     function. Checked by no type (`@ts-nocheck`), as the
//                                     generated module of a host face is checked by none.
//
// `bun scripts/bake-libm.ts` writes the file. `--check` writes nothing and fails when the file
// is missing or stale; `src/core/libm/libm.test.ts` holds the same.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileLibmSource } from '../src/compiler/ts/libm-source.js';
import { generateModuleJs } from '../src/core/cpu-codegen.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The libm's source and its baked JavaScript form, by path from the repository root. */
export const LIBM_SOURCE = 'src/core/libm/trig.shade.ts';
export const LIBM_GENERATED = 'src/core/libm/trig.generated.ts';

/** The members of the factory's `$` that the generated code may read: what `LibmHost` of
 *  `src/core/libm/index.ts` holds, and `F`, which `makeTrig` fills. */
const HOST_MEMBERS: ReadonlySet<string> = new Set(['B', 'L', 'F', 'intDiv', 'intRem']);

/** The baked file's text for the libm source `text`. Pure. */
export function bakeLibm(text: string): string {
  const compiled = compileLibmSource(text, LIBM_SOURCE);
  const errors = compiled.diagnostics.filter((d) => d.category === 'error');
  if (errors.length > 0) {
    throw new Error(
      `${LIBM_SOURCE} does not compile:\n` +
        errors.map((d) => `  ${d.code} line ${String(d.line)}: ${d.message}`).join('\n'),
    );
  }
  const generated = generateModuleJs(compiled.module, { precision: 'f32' });
  if (generated.fallbacks.length > 0) {
    throw new Error(
      `${LIBM_SOURCE}: no JavaScript was generated for ${generated.fallbacks.join(', ')}`,
    );
  }
  // A member the host does not hold would be `undefined` at the first call, so it fails here.
  for (const m of generated.factorySource.matchAll(/\$\.([A-Za-z_]\w*)/g)) {
    if (!HOST_MEMBERS.has(m[1]!)) {
      throw new Error(`${LIBM_SOURCE}: the generated code reads $.${m[1]!}, which LibmHost lacks`);
    }
  }
  return (
    `// Generated by scripts/bake-libm.ts from ${LIBM_SOURCE}. Do not edit; run \`bun run bake:libm\`.\n` +
    `// @ts-nocheck\n` +
    `export function trigFactory($) {\n${generated.factorySource}\n}\n`
  );
}

if (import.meta.main) {
  const check = process.argv.includes('--check');
  const text = bakeLibm(readFileSync(join(ROOT, LIBM_SOURCE), 'utf8'));
  const path = join(ROOT, LIBM_GENERATED);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
      console.error(`${LIBM_GENERATED} is missing or stale. Run \`bun run bake:libm\`.`);
      process.exit(1);
    }
    console.log(`${LIBM_GENERATED} is current.`);
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${LIBM_GENERATED}`);
  }
}
