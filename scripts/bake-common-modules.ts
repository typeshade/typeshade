// ═══ The host faces of the common modules, baked from their shader modules (change 0072) ═══
//
// `typeshade/algorithms` and `typeshade/random` are shader packages inside this package (Rule
// 11.20): their functions are written in `"use typeshade"` under `src/algorithms/` and
// `src/random/`, and a host imports the subpath as it imports any package. A consumer's build has
// the Vite plugin or `tshc sync` to make the host face of a shader module; this package ships its
// own faces, so they are baked here from `index.shade.ts` of each module with `hostFace()`, the
// function the plugin and `tshc` run, built for fusion:
//
//   face.ts   the generated module (`hostFace().code`): the CPU twin of each function, each
//             kernel's face with the facts the planner reads, and the manifest. Checked by no
//             type (`@ts-nocheck`), as the plugin's output is checked by none.
//   view.ts   the declarations (`hostFace().view`), the types of each export.
//   index.ts  what the subpath exports: each export of the face under its public name, typed by
//             the view, with the doc comment of its shader source; a map or a reduction named
//             `<op>Map` or `<op>All` in the shader module, since a kernel function cannot carry a
//             builtin's name, is exported under the builtin's name (proposal 0072, Amendment 1).
//
// `bun scripts/bake-common-modules.ts` writes the three files of each module. `--check` writes
// nothing and fails when one is missing or stale; `src/common-modules.test.ts` holds the same.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { hostFace } from '../src/compiler/ts/host-face.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** A common module: its directory under `src/`, and the host files that join the baked ones. */
export interface CommonModule {
  readonly dir: string;
  /** Lines appended to `index.ts`: the exports that are plain JavaScript (`generator`). */
  readonly extraExports: readonly string[];
}

export const COMMON_MODULES: readonly CommonModule[] = [
  { dir: 'src/algorithms', extraExports: [] },
  { dir: 'src/random', extraExports: ["export { generator } from './generator.js';"] },
];

/** The public name of an export: a kernel named `<op>Map` or `<op>All` for a builtin's name is
 *  exported under that name. */
export function publicName(name: string): string {
  return name.replace(/(Map|All)$/, '');
}

const HEADER = (from: string): string =>
  `// Generated by scripts/bake-common-modules.ts from ${from}. Do not edit; run \`bun scripts/bake-common-modules.ts\`.\n`;

/** The doc comment written above `export function <name>` in the shader sources, by name. */
function docsOf(sources: readonly string[]): Map<string, string> {
  const docs = new Map<string, string>();
  for (const text of sources) {
    const re = /(\/\*\*[\s\S]*?\*\/)\s*\nexport function (\w+)\(/g;
    for (let m = re.exec(text); m !== null; m = re.exec(text)) docs.set(m[2]!, m[1]!);
  }
  return docs;
}

/** The three baked files of a module, as text. Pure: `read` reads the files it names. */
export async function bakeCommonModule(
  module: CommonModule,
  read: (file: string) => string | undefined,
): Promise<{ face: string; view: string; index: string }> {
  // The compiler is given the entry by its path from the repository root, and reads the files
  // it imports by the same kind of path: the face carries the entry's name (`fuse.origin`), and
  // a name that held the checkout's absolute path made the bake differ between two machines.
  const entry = `${module.dir}/index.shade.ts`;
  const text = read(join(ROOT, entry));
  if (text === undefined) throw new Error(`cannot read ${entry}`);
  const seen = new Set<string>([join(ROOT, entry)]);
  const reading = (file: string): string | undefined => {
    const path = isAbsolute(file) ? file : join(ROOT, file);
    const t = read(path);
    if (t !== undefined) seen.add(path);
    return t;
  };
  const g = hostFace(text, { fileName: entry, fuse: true, readDocument: reading });
  const errors = g.diagnostics.filter((d) => d.category === 'error');
  if (errors.length > 0 || g.code === undefined || g.view === undefined || g.exports === undefined)
    throw new Error(
      `${module.dir}: ${errors.map((d) => `${d.code} ${d.message}`).join('\n') || 'no face'}`,
    );
  const from = `${module.dir}/index.shade.ts`;
  const face = `${HEADER(from)}// @ts-nocheck\n${g.code}`;
  const view = `${HEADER(from)}${g.view}`;
  const docs = docsOf([...seen].map((f) => read(f) ?? ''));
  const lines = [
    HEADER(from),
    `// The host face of \`typeshade/${module.dir.slice('src/'.length)}\` (change 0072, Rule 11.20): each`,
    '// export runs the function of the shader module on the tiers `configure({ prefer })` orders, as a',
    '// kernel function (Rule 11.8) or a plain function on the CPU (surface §64), typed by the view.',
    '',
    "import * as face from './face.js';",
    "import type * as view from './view.js';",
    '',
  ];
  for (const e of g.exports) {
    if (e.kind !== 'kernel' && e.kind !== 'function') continue;
    const doc = docs.get(e.name);
    if (doc !== undefined) lines.push(doc);
    lines.push(
      `export const ${publicName(e.name)}: typeof view.${e.name} = face.${e.name} as typeof view.${e.name};`,
    );
  }
  for (const extra of module.extraExports) lines.push(extra);
  lines.push('');
  // `index.ts` is checked by `format:check` as every source file is; the generated module and the
  // declarations are not (`.prettierignore`), as a host view is not.
  const indexFile = join(ROOT, module.dir, 'index.ts');
  const index = await format(lines.join('\n'), {
    ...(await resolveConfig(indexFile)),
    filepath: indexFile,
  });
  return { face, view, index };
}

/** The files a module bakes to, by name. */
export function bakedFiles(module: CommonModule): Record<'face' | 'view' | 'index', string> {
  return {
    face: join(ROOT, module.dir, 'face.ts'),
    view: join(ROOT, module.dir, 'view.ts'),
    index: join(ROOT, module.dir, 'index.ts'),
  };
}

const readDisk = (file: string): string | undefined =>
  existsSync(file) ? readFileSync(file, 'utf8') : undefined;

if (import.meta.main) {
  const check = process.argv.includes('--check');
  let status = 0;
  for (const module of COMMON_MODULES) {
    const baked = await bakeCommonModule(module, readDisk);
    const files = bakedFiles(module);
    for (const key of ['face', 'view', 'index'] as const) {
      const current = readDisk(files[key]);
      if (current === baked[key]) continue;
      if (check) {
        process.stderr.write(
          `${files[key]} is ${current === undefined ? 'missing' : 'stale'}; run bun scripts/bake-common-modules.ts\n`,
        );
        status = 1;
      } else {
        writeFileSync(files[key], baked[key]);
        process.stdout.write(`wrote ${files[key]}\n`);
      }
    }
  }
  process.exit(status);
}
