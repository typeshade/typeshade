// ═══ The capability coverage table: validated, rendered and baked ═══
//
// WHAT IT IS. `docs/capability-coverage.md` is the coverage table of proposal 0059: every capability
// of WebGPU and of WebGL2 with exactly one status per target (Rules 11.14 to 11.18 of
// docs/language-design.md). Its rows are the typed data of `src/core/coverage/`. This script holds
// those rows to the sources they classify (scripts/capability-sources.ts), to the rules document,
// to the proposals and to the code that the rules name. It then writes the table, and the counts
// and the WebGL2-only list that Appendix C of docs/language-design.md holds between its markers.
//
// WHY IT EXISTS. A row goes stale in four ways: (1) a source gains a member that no row covers (a
// version bump); (2) a row names a member that no source has; (3) a row names a test, a proposal,
// a hatch or a line that is no longer there; (4) a rule or a hatch of Rule 11.17 changes its text.
// `validate()` runs every check of `CHECKS`, and together they cover the four ways. Each message names
// its row, and a message about one cell also names the target.
//
// THE CHECKS. One exported function per check, so a test can run a doctored input through the same
// code. In order: `checkCoverage` (every source key has one row), `checkStray` (no row names a key
// that no source has), `checkHatchList` (ESCAPE_HATCHES is the list of Rule 11.17), `checkTyped`
// (a typed cell names a test that exists: a test file, a file a gate runs, or a journey), `checkRefused`
// (a refused cell names a `Rule N.M` that the rules document defines, and a portable spelling),
// `checkPlanned` (a planned cell names a proposal in changes/ whose status is draft or accepted),
// `checkRaw` (a raw cell names a hatch), `checkGap` (a gap cell names a group and a positive issue),
// `checkNa` (an n/a cell gives a reason), `checkWebGl2Only` (Rule 11.16), `checkHatchDocs` (each
// hatch is documented in its declaration's JSDoc), `checkSubGaps` (a sub-gap names a group and a
// positive issue) and `checkEvidence` (the evidence follows its grammar: every segment names a file of
// the tree, every line it cites is in range, and no evidence names an issue).
//
// THE CONTEXT. `loadContext()` reads what the checks compare the rows with: the rule numbers and the
// Rule 11.17 text, the status of each proposal, the files the `gate:*` scripts run, the rows of
// TYPESHADE_EXTENSIONS, the §10 capabilities and the JSDoc of the escape hatches. Each is read from
// its one source, never copied into this file.
//
// TO REGENERATE (from the package root):
//
//   bun run bake:capability-coverage                  writes docs/capability-coverage.md and Appendix C
//   bun scripts/bake-capability-coverage.ts --check   writes nothing; exits 1 and names each file that would change
//
// The script writes even when `validate()` finds defects: the coverage test is the gate, and it fails
// on the same defects. The script prints the number of defects for each check.
//
// WHAT TO CHECK AFTER A BAKE. Read the counts table and the gap register. A status that moved, a row
// that appeared or a row that vanished is a change of the table: read it as one (Rule 11.4 and Rule
// 11.15), and name the row and the reason in the pull request.

