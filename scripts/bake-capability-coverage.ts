/** The Source column: the location of each key; for more than two keys, the first and a count. */
function sourceOf(row: Row, locations: ReadonlyMap<string, string>): string {
  const found = row.covers.map((key) => locations.get(key) ?? 'no source');
  const shown = found.length <= 2 ? found : [found[0]!];
  const more = found.length > 2 ? ` +${found.length - 1} more` : '';
  return `${shown.map((loc) => `\`${loc}\``).join('; ')}${more}`;
}

/** One table of the classification, in the compact form. Its columns are Kind, Name, Source, Evidence,
 *  WebGPU, WebGL2 and Note. Note is the row's own note (`Row.note`), last; it is empty when the row
 *  has none. Every cell goes through `esc`, so a `|` in any of them stays inside its cell. */
function tableOf(rows: readonly Row[], locations: ReadonlyMap<string, string>): string {
  return table(
    ['Kind', 'Name', 'Source', 'Evidence', 'WebGPU', 'WebGL2', 'Note'],
    rows.map((row) =>
      [
        row.kind,
        row.name,
        sourceOf(row, locations),
        row.evidence,
        cellText(row.webgpu),
        cellText(row.webgl2),
        row.note ?? '',
      ].map(esc),
    ),
  );
}

function webgl2OnlyLines(rows: readonly Row[]): string[] {
  return rows
    .filter((r) => r.webgl2Only)
    .map((r) =>
      escText(`- ${r.name}: WebGL2 ${cellText(r.webgl2)}; door: ${doorText(r.webgl2Only!)}`),
    );
}

/** One group of the gap register: its gap cells and sub-gaps, per target, and the issues named. */
interface GroupEntry {
  readonly target: string;
  readonly name: string;
  readonly kind: string;
  readonly issue: number | undefined;
}

function groupEntries(rows: readonly Row[], group: GapGroup): GroupEntry[] {
  const out: GroupEntry[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const cell = row[target.key];
      if (cell.status === 'gap' && cell.group === group) {
        out.push({ target: target.label, name: row.name, kind: 'gap', issue: cell.issue });
      }
      const sub = subGapOf(cell);
      if (sub && sub.group === group) {
        out.push({
          target: target.label,
          name: row.name,
          kind: `inside ${cell.status}`,
          issue: sub.issue,
        });
      }
    }
  }
  return out;
}

function gapRegister(rows: readonly Row[]): string[] {
  const out = [
    '## Gap register',
    '',
    'A gap cell has none of the other five statuses: typed, raw, refused, planned or n/a. A sub-gap is the part of a typed, raw or planned cell that has no typed spelling. Each group lists both, and the issues they name.',
  ];
  for (const group of Object.keys(GAP_GROUPS).map(Number) as GapGroup[]) {
    const entries = groupEntries(rows, group);
    const gapCells = (t: string): number =>
      entries.filter((e) => e.target === t && e.kind === 'gap').length;
    const subGaps = (t: string): number =>
      entries.filter((e) => e.target === t && e.kind !== 'gap').length;
    const issues = [
      ...new Set(entries.map((e) => e.issue).filter((i): i is number => i !== undefined)),
    ].sort((a, b) => a - b);
    out.push(
      '',
      `### Group ${group}: ${GAP_GROUPS[group]}`,
      '',
      `Gap cells: WebGPU ${gapCells('WebGPU')}, WebGL2 ${gapCells('WebGL2')}. Sub-gaps: WebGPU ${subGaps('WebGPU')}, WebGL2 ${subGaps('WebGL2')}. Issues named: ${issues.length ? issues.map((i) => `#${i}`).join(', ') : 'none'}.`,
    );
    if (entries.length === 0) {
      out.push('', 'None.');
      continue;
    }
    out.push(
      '',
      ...entries.map((e) =>
        escText(
          `- ${e.target}, ${e.name}: ${e.kind}${e.issue === undefined ? '' : ` (#${e.issue})`}`,
        ),
      ),
    );
  }
  return out;
}

/** The generated document. It is not run through Prettier: docs/capability-coverage.md is in
 *  .prettierignore, its tables have one line per row with no padding, and the coverage test compares
 *  this text byte for byte. */
export function render(
  rows: readonly Row[],
  sources: readonly SourceMember[],
  pinned: Pinned,
): string {
  const locations = new Map(sources.map((s) => [s.key, s.location]));
  const flagged = rows.filter((r) => r.webgl2Only);
  const sections: string[] = [
    SKIP_LINE,
    '# Capability coverage',
    'This file is generated by `scripts/bake-capability-coverage.ts`. Do not edit it by hand. `src/core/spec-conformance/capability-coverage.test.ts` holds it to its sources. Appendix C of `docs/language-design.md` (Rules 11.14 to 11.18) describes it.',
    '## Sources and versions',
    configurationTable(pinned),
    '## Counts',
    'Each count is one status of one target. The rows column counts the rows of the table. A sub-gap is counted in the gap register, not here.',
    countsTable(rows, true),
  ];
  for (const t of TABLES) {
    sections.push(
      `## Table ${t}: ${TABLE_TITLES[t]}`,
      tableOf(
        rows.filter((r) => r.table === t),
        locations,
      ),
    );
  }
  sections.push(
    '## WebGL2-only capabilities',
    `${flagged.length} capabilities are flagged WebGL2-only. Each enters the surface by the door it names (Rule 11.16).`,
    webgl2OnlyLines(rows).join('\n'),
    gapRegister(rows).join('\n'),
  );
  return `${sections.join('\n\n')}\n`;
}

/** The lines between the markers of Appendix C: the counts of all four tables and the WebGL2-only
 *  list with each door. The markers themselves are not part of it. */
export function renderAppendix(rows: readonly Row[]): string {
  const flagged = rows.filter((r) => r.webgl2Only);
  return [
    `The coverage table has ${rows.length} rows in four tables, A to D. Each row has one status on each target.`,
    '',
    'The counts below cover all four tables. A sub-gap is not counted here; the gap register of `docs/capability-coverage.md` lists it.',
    '',
    countsTable(rows, true),
    '',
    `${flagged.length} capabilities are flagged WebGL2-only. Each enters the surface by the door it names (Rule 11.16).`,
    '',
    webgl2OnlyLines(rows).join('\n'),
    '',
  ].join('\n');
}

/** Prettier with the repository's configuration for the file the text is written to. It formats the
 *  Appendix C block of the design document, which is not in .prettierignore; the generated table is
 *  not formatted (see `render`). */
export async function format(text: string, file: string = DESIGN): Promise<string> {
  const config = (await resolveConfig(join(ROOT, file))) ?? {};
  return prettierFormat(text, { ...config, parser: 'markdown' });
}

/** The design document with the lines between its two markers replaced. The markers stay byte for byte. */
export function spliceAppendix(design: string, block: string): string {
  const lines = design.split('\n');
  const begins = lines.flatMap((l, i) => (l.startsWith(BEGIN) ? [i] : []));
  const ends = lines.flatMap((l, i) => (l.trim() === END ? [i] : []));
  if (begins.length !== 1 || ends.length !== 1) {
    throw new Error(
      `${DESIGN} must hold one "${BEGIN}" marker and one "${END}" marker; found ${begins.length} and ${ends.length}`,
    );
  }
  const [begin] = begins;
  const [end] = ends;
  if (end! <= begin!) throw new Error(`${DESIGN}: the end marker comes before the begin marker`);
  return [
    ...lines.slice(0, begin! + 1),
    '',
    ...block.trimEnd().split('\n'),
    '',
    ...lines.slice(end),
  ].join('\n');
}

// ─── the command ──────────────────────────────────────────────────────────────────────────────

async function main(args: readonly string[]): Promise<number> {
  const check = args.includes('--check');
  const pkg = JSON.parse(read(ROOT, PACKAGE)) as { devDependencies?: Record<string, string> };
  const mismatches = pinMismatches(
    { webgpuTypes: PINNED.webgpuTypes.version, typescript: PINNED.typescript.version },
    {
      webgpuTypes: pkg.devDependencies?.['@webgpu/types'] ?? 'no pin',
      typescript: pkg.devDependencies?.typescript ?? 'no pin',
    },
  );
  if (mismatches.length > 0) {
    for (const mismatch of mismatches) console.error(mismatch);
    console.error(
      'install the pinned versions (bun install), then bake again; nothing was written',
    );
    return 1;
  }
  const sources = readSources(ROOT);
  const ctx = loadContext(ROOT);
  const doc = render(COVERAGE_ROWS, sources, PINNED);
  const block = await format(renderAppendix(COVERAGE_ROWS), DESIGN);
  const design = spliceAppendix(read(ROOT, DESIGN), block);

  console.log(`capability coverage: ${COVERAGE_ROWS.length} rows, ${sources.length} source keys`);
  for (const t of TABLES) {
    const rows = COVERAGE_ROWS.filter((r) => r.table === t);
    for (const target of TARGETS) {
      const c = countOf(rows, target);
      console.log(
        `  table ${t} ${target.label}: typed ${c.typed}, raw ${c.raw}, refused ${c.refused}, planned ${c.planned}, gap ${c.gap}, n/a ${c['n/a']} (rows ${c.rows})`,
      );
    }
  }
  let defects = 0;
  for (const c of CHECKS) {
    const n = c.run(COVERAGE_ROWS, sources, ctx).length;
    defects += n;
    console.log(`  defects in ${c.name}: ${n}`);
  }
  console.log(`defects: ${defects} (the coverage test is the gate)`);

  if (check) {
    const stale = [
      readIfExists(ROOT, DOC) === doc ? undefined : DOC,
      read(ROOT, DESIGN) === design ? undefined : DESIGN,
    ].filter((f): f is string => f !== undefined);
    if (stale.length > 0) {
      console.error(`out of date: ${stale.join(', ')}; run bun run bake:capability-coverage`);
      return 1;
    }
    console.log('up to date');
    return 0;
  }
  writeFileSync(join(ROOT, DOC), doc);
  writeFileSync(join(ROOT, DESIGN), design);
  console.log(`wrote ${DOC} and the Appendix C block of ${DESIGN}`);
  return 0;
}

if (import.meta.main) {
  process.exit(await main(process.argv.slice(2)));
}
