// ─── reading the context ──────────────────────────────────────────────────────────────────────

function read(root: string, file: string): string {
  return readFileSync(join(root, file), 'utf8');
}

/** The text of a file, or the empty string when the file does not exist yet (a first bake). */
function readIfExists(root: string, file: string): string {
  return existsSync(join(root, file)) ? read(root, file) : '';
}

/** The text of one paragraph: from `start` to the next blank line, on one line. */
function paragraphOf(text: string, start: string): string {
  const at = text.indexOf(start);
  if (at < 0) throw new Error(`docs/language-design.md has no "${start}" paragraph`);
  const end = text.indexOf('\n\n', at);
  return text
    .slice(at, end < 0 ? undefined : end)
    .replace(/\s+/g, ' ')
    .trim();
}

/** The hatches Rule 11.17 lists: the backticked names between "exactly these:" and "Each is documented". */
export function ruleHatches(ruleText: string): string[] {
  const from = ruleText.indexOf('exactly these:');
  const to = ruleText.indexOf('Each is documented');
  if (from < 0 || to < from) {
    throw new Error('Rule 11.17 does not list its escape hatches in the form the bake reads');
  }
  return [...ruleText.slice(from, to).matchAll(/`([^`]+)`/g)].map((m) => m[1]!);
}

/** The names of the rows of TYPESHADE_EXTENSIONS, read from the test file as data: the table
 *  lives in that test, and the test is its one authority. */
export function extensionRowNames(testText: string): Set<string> {
  const start = testText.indexOf('const TYPESHADE_EXTENSIONS');
  const end = start < 0 ? -1 : testText.indexOf('\n];', start);
  if (start < 0 || end < 0) throw new Error(`${SURFACE_NAMES} has no TYPESHADE_EXTENSIONS array`);
  const names = [...testText.slice(start, end).matchAll(/\bname:\s*'([^']+)'/g)].map((m) => m[1]!);
  if (names.length < EXTENSION_FLOOR) {
    throw new Error(
      `${SURFACE_NAMES}: ${names.length} extension rows read, at least ${EXTENSION_FLOOR} expected`,
    );
  }
  return new Set(names);
}

/** The files that the `gate:*` scripts run, taken from their command strings. */
export function gateFilesOf(pkg: {
  readonly scripts?: Readonly<Record<string, string>>;
}): Set<string> {
  const files = new Set<string>();
  for (const [name, command] of Object.entries(pkg.scripts ?? {})) {
    if (!name.startsWith('gate:')) continue;
    for (const token of command.split(/\s+/)) {
      if (/\.(?:ts|tsx|mjs|js)$/.test(token)) files.add(token.replace(/^\.\//, ''));
    }
  }
  if (files.size === 0) throw new Error('package.json has no gate:* script that runs a file');
  return files;
}

/** The `status:` of each proposal in `changes/`, read from its front matter. */
export function proposalStatuses(root: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const name of readdirSync(join(root, 'changes'))) {
    const id = /^(\d{4})-.+\.md$/.exec(name)?.[1];
    if (!id) continue;
    const front = /^---\n([\s\S]*?)\n---/.exec(read(root, `changes/${name}`))?.[1] ?? '';
    const status = /^status:\s*['"]?([a-z-]+)/m.exec(front)?.[1];
    if (!status) throw new Error(`changes/${name} has no status in its front matter`);
    out.set(id, status);
  }
  if (out.size === 0) throw new Error('changes/ holds no proposal');
  return out;
}

/** A JSDoc block as one line, its `*` gutter removed. */
function blockText(block: string): string {
  return block
    .replace(/^\/\*\*|\*\/$/g, '')
    .split('\n')
    .map((line) => line.replace(/^\s*\*?\s?/, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
}

interface HatchSite {
  /** The interface or class that declares the member, when the block sits in one. */
  readonly owner: string | undefined;
  /** The JSDoc of that interface or class, as one line. */
  readonly ownerDoc: string;
  /** The member the block documents, when the block precedes a member. */
  readonly member: string | undefined;
  /** The block, as one line. */
  readonly doc: string;
}

const DECLARATION =
  /^(?:export )?(?:declare )?(?:interface|class|type|function|const|let|var) (\w+)/gm;
const MEMBER = /^\s*(?:readonly\s+)?(\w+)\??\s*[:(<]/;

/** Every JSDoc block of one file that carries the Rule 11.17 sentence, with what it documents. */
export function hatchSites(text: string): HatchSite[] {
  const decls = [...text.matchAll(DECLARATION)];
  const sites: HatchSite[] = [];
  for (const block of text.matchAll(/\/\*\*[\s\S]*?\*\//g)) {
    const doc = blockText(block[0]);
    if (!doc.includes(HATCH_MARK)) continue;
    const at = block.index ?? 0;
    let decl: RegExpMatchArray | undefined;
    for (const d of decls) if ((d.index ?? 0) < at) decl = d;
    const before = decl ? text.slice(0, decl.index ?? 0).trimEnd() : '';
    const ownerDoc = before.endsWith('*/')
      ? blockText(before.slice(before.lastIndexOf('/**')))
      : '';
    sites.push({
      owner: decl?.[1],
      ownerDoc,
      member: MEMBER.exec(text.slice(at + block[0].length))?.[1],
      doc,
    });
  }
  return sites;
}

/** Whether one hatch of ESCAPE_HATCHES is documented: `Owner.member` by a member of that owner,
 *  `createRuntime({ device })` by the option `device` of an interface the createRuntime docs name,
 *  and a host object (`GPUBuffer`) by any such sentence that names it. */
export function hatchDocumented(hatch: string, sites: readonly HatchSite[]): boolean {
  const dotted = /^(\w+)\.(\w+)/.exec(hatch);
  if (dotted) {
    const [, owner, member] = dotted;
    return sites.some((s) => s.member === member && s.owner === owner);
  }
  const option = /^(\w+)\(\{ (\w+) \}\)$/.exec(hatch);
  if (option) {
    const [, fn, member] = option;
    return sites.some((s) => s.member === member && s.ownerDoc.includes(fn!));
  }
  const name = new RegExp(`\\b${hatch.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`);
  return sites.some((s) => name.test(s.doc));
}

/** Each hatch of ESCAPE_HATCHES, documented or not, given the texts of the files that declare them. */
export function hatchDocumentsOf(texts: readonly string[]): Map<string, boolean> {
  const sites = texts.flatMap((text) => hatchSites(text));
  if (sites.length === 0)
    throw new Error(`no escape hatch is documented in ${HATCH_FILES.join(', ')}`);
  return new Map(ESCAPE_HATCHES.map((h) => [h, hatchDocumented(h, sites)]));
}

function hatchDocumentation(root: string): Map<string, boolean> {
  return hatchDocumentsOf(HATCH_FILES.map((file) => read(root, file)));
}

/** Everything the checks compare the rows with, read from its one source. */
export function loadContext(root: string = ROOT): Context {
  return {
    root,
    definedRules: definedRules(root),
    rule1117: paragraphOf(read(root, DESIGN), RULE_1117),
    proposals: proposalStatuses(root),
    gateFiles: gateFilesOf(JSON.parse(read(root, PACKAGE)) as { scripts?: Record<string, string> }),
    extensionRows: extensionRowNames(read(root, SURFACE_NAMES)),
    capabilities: new Set(ALL_CAPABILITIES),
    hatchDocs: hatchDocumentation(root),
  };
}

