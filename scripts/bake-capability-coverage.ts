/** The label of a target in the messages: the `label` of TARGETS. */
export type TargetLabel = Target['label'];

/** A row as the messages name it: its name and its first source key. The test reads the messages
 *  through these builders, so a change of wording is one change, and a filter that finds nothing
 *  is caught by the test's positive control. */
export const rowLabel = (row: Row): string => `"${row.name}" (${row.covers[0] ?? 'no key'})`;
/** One cell of a row as the messages name it: the target, then the row. */
export const cellLabel = (row: Row, target: TargetLabel): string =>
  `${target} cell of ${rowLabel(row)}`;
/** The evidence of a row as the messages name it. */
export const evidenceLabel = (row: Row): string => `evidence of ${rowLabel(row)}`;

/** Names a row and its target: the cell's label. */
const where = (row: Row, target: Target): string => cellLabel(row, target.label);

/** Rule 11.14: every source key is covered by exactly one row. */
export function checkCoverage(rows: readonly Row[], sources: readonly SourceMember[]): string[] {
  const owners = new Map<string, Row[]>();
  for (const row of rows) {
    for (const key of row.covers) owners.set(key, [...(owners.get(key) ?? []), row]);
  }
  const out: string[] = [];
  for (const source of sources) {
    const covering = owners.get(source.key) ?? [];
    if (covering.length === 0) {
      out.push(`source key ${source.key} (${source.location}) has no row (Rule 11.14)`);
    } else if (covering.length > 1) {
      const names = covering.map((r) => rowLabel(r)).join(', ');
      out.push(
        `source key ${source.key} is covered by ${covering.length} rows: ${names} (Rule 11.14)`,
      );
    }
  }
  return out;
}

/** Rule 11.15: no row covers a key that no source has, and no row covers nothing. */
export function checkStray(rows: readonly Row[], sources: readonly SourceMember[]): string[] {
  const keys = new Set(sources.map((s) => s.key));
  const out: string[] = [];
  for (const row of rows) {
    if (row.covers.length === 0) out.push(`row ${rowLabel(row)} covers no key (Rule 11.15)`);
    for (const key of row.covers) {
      if (!keys.has(key))
        out.push(`row ${rowLabel(row)} covers ${key}, which no source has (Rule 11.15)`);
    }
  }
  return out;
}

/** Rule 11.17: ESCAPE_HATCHES is the list the rule names, in its order. */
export function checkHatchList(ctx: Context): string[] {
  const listed = ruleHatches(ctx.rule1117);
  const same =
    listed.length === ESCAPE_HATCHES.length && listed.every((h, i) => h === ESCAPE_HATCHES[i]);
  return same
    ? []
    : [
        `ESCAPE_HATCHES (${ESCAPE_HATCHES.join(', ')}) differs from the names Rule 11.17 lists (${listed.join(', ')}) (Rule 11.17)`,
      ];
}

/** Why a path cannot name a file of the repository, or undefined when it may: an absolute path (a
 *  Windows drive included) and a path with a `..` segment are refused. Every path the table cites
 *  is repository-relative, so the test files and the evidence both use this. */
export function pathDefect(path: string): string | undefined {
  if (isAbsolute(path) || /^[A-Za-z]:[\\/]/.test(path)) return 'is an absolute path';
  if (path.split('/').includes('..')) return "leaves the repository through '..'";
  return undefined;
}

/** Why a test path is not a test (Rule 11.18), or undefined when it is one. A test is a `*.test.ts`
 *  file, a file a `gate:*` script runs, or a journey: the directory `journeys/<name>` itself, or a file
 *  under it, where `<name>` does not start with `_`. `journeys/README.md` and the `journeys/_*`
 *  harnesses are not journeys. Any other directory is not a test, and `pathDefect` refuses an absolute
 *  path or a path with a `..` segment. */
export function testDefect(path: string, ctx: Context): string | undefined {
  const refused = pathDefect(path);
  if (refused !== undefined) return refused;
  const full = join(ctx.root, path);
  if (!existsSync(full)) return 'does not exist';
  const directory = statSync(full).isDirectory();
  const journey = /^journeys\/([^/]+)(\/.*)?$/.exec(path);
  if (journey && !journey[1]!.startsWith('_')) {
    const inside = journey[2] !== undefined;
    if (inside ? !directory : directory) return undefined;
  }
  if (directory) return 'is a directory, not a test';
  if (path.endsWith('.test.ts') || ctx.gateFiles.has(path)) return undefined;
  return 'is not a test';
}

/** A typed cell names a test that exists and is a test (Rule 11.18), see `testDefect`. */
export function checkTyped(rows: readonly Row[], ctx: Context): string[] {
  const out: string[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const cell = row[target.key];
      if (cell.status !== 'typed') continue;
      if (!cell.test) {
        out.push(`${where(row, target)} names no test (Rule 11.18)`);
        continue;
      }
      const defect = testDefect(cell.test, ctx);
      if (defect !== undefined) {
        out.push(`${where(row, target)} names ${cell.test}, which ${defect} (Rule 11.18)`);
      }
    }
  }
  return out;
}

/** A refused cell names a rule of the form `Rule N.M` that docs/language-design.md defines, and a
 *  portable spelling. A rule text that holds a defined number but is not that form is a defect. */
export function checkRefused(rows: readonly Row[], ctx: Context): string[] {
  const out: string[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const cell = row[target.key];
      if (cell.status !== 'refused') continue;
      const rule = /^Rule (\d+\.\d+)$/.exec(cell.rule)?.[1];
      if (rule === undefined) {
        out.push(
          `${where(row, target)} names "${cell.rule}", which is not of the form "Rule N.M" (Rule 11.18)`,
        );
      } else if (!ctx.definedRules.has(rule)) {
        out.push(
          `${where(row, target)} names ${cell.rule}, which docs/language-design.md does not define (Rule 11.18)`,
        );
      }
      if (!cell.portable.trim())
        out.push(`${where(row, target)} gives no portable spelling (Rule 11.18)`);
    }
  }
  return out;
}

/** The statuses of a proposal that a planned cell may name: an open one or an accepted one (proposal
 *  0059, the statuses table: "a proposal in changes/ with status: draft or accepted names it"). */
const PLANNED_STATUSES: readonly string[] = ['draft', 'accepted'];

/** A planned cell names a four-digit id of a proposal in `changes/` whose status is draft or accepted.
 *  A missing file, and every other status (implemented, archived, withdrawn), is a defect. */
export function checkPlanned(rows: readonly Row[], ctx: Context): string[] {
  const out: string[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const cell = row[target.key];
      if (cell.status !== 'planned') continue;
      if (!/^\d{4}$/.test(cell.proposal)) {
        out.push(
          `${where(row, target)} names proposal ${cell.proposal}, which is not a four-digit id (Rule 11.18)`,
        );
        continue;
      }
      const status = ctx.proposals.get(cell.proposal);
      if (status === undefined) {
        out.push(
          `${where(row, target)} names proposal ${cell.proposal}, which has no file in changes/ (Rule 11.18)`,
        );
      } else if (!PLANNED_STATUSES.includes(status)) {
        out.push(
          `${where(row, target)} names proposal ${cell.proposal}, which is ${status}; a planned cell names a draft or accepted proposal (Rule 11.18)`,
        );
      }
    }
  }
  return out;
}

/** A raw cell names one hatch of ESCAPE_HATCHES. */
export function checkRaw(rows: readonly Row[]): string[] {
  const out: string[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const cell = row[target.key];
      if (cell.status === 'raw' && !(ESCAPE_HATCHES as readonly string[]).includes(cell.hatch)) {
        out.push(
          `${where(row, target)} names hatch ${cell.hatch}, which Rule 11.17 does not list (Rule 11.17)`,
        );
      }
    }
  }
  return out;
}

const isPositiveInteger = (n: unknown): boolean => Number.isInteger(n) && (n as number) > 0;
const isGroup = (group: number): boolean => Object.keys(GAP_GROUPS).includes(String(group));

/** A gap cell names a group of GAP_GROUPS, a note and, when it has one, a positive issue. */
export function checkGap(rows: readonly Row[]): string[] {
  const out: string[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const cell = row[target.key];
      if (cell.status !== 'gap') continue;
      if (!isGroup(cell.group))
        out.push(
          `${where(row, target)} names gap group ${cell.group}, which GAP_GROUPS does not define`,
        );
      if (!cell.note.trim()) out.push(`${where(row, target)} is a gap with no note (Rule 11.18)`);
      if (cell.issue !== undefined && !isPositiveInteger(cell.issue)) {
        out.push(
          `${where(row, target)} names issue ${cell.issue}, which is not a positive integer`,
        );
      }
    }
  }
  return out;
}

/** An n/a cell gives its reason. */
export function checkNa(rows: readonly Row[]): string[] {
  const out: string[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const cell = row[target.key];
      if (cell.status === 'n/a' && !cell.reason.trim())
        out.push(`${where(row, target)} is n/a with no reason (Rule 11.18)`);
    }
  }
  return out;
}

/** Rule 11.16: a WebGL2-only row is typed on WebGL2 only behind a door that exists, and is n/a on
 *  WebGL2 only with a rule number in its reason. */
export function checkWebGl2Only(rows: readonly Row[], ctx: Context): string[] {
  const out: string[] = [];
  for (const row of rows) {
    const door: Door | undefined = row.webgl2Only;
    if (!door) continue;
    const cell = row.webgl2;
    const target = WEBGL2;
    if (cell.status === 'typed') {
      if (door.door === '§9.3' && !ctx.extensionRows.has(door.row)) {
        out.push(
          `${where(row, target)} is typed behind §9.3 row "${door.row}", which TYPESHADE_EXTENSIONS does not hold (Rule 11.16)`,
        );
      } else if (door.door === '§10' && !ctx.capabilities.has(door.capability)) {
        out.push(
          `${where(row, target)} is typed behind §10 capability ${door.capability}, which the capability table does not hold (Rule 11.16)`,
        );
      } else if (door.door === 'none') {
        out.push(`${where(row, target)} is typed with no door (Rule 11.16)`);
      }
    }
    if (cell.status === 'n/a') {
      const rules = [...cell.reason.matchAll(/Rule (\d+\.\d+)/g)].map((m) => m[1]!);
      if (!rules.some((r) => ctx.definedRules.has(r))) {
        out.push(`${where(row, target)} is n/a with no rule number in its reason (Rule 11.16)`);
      }
    }
  }
  return out;
}

/** Rule 11.17, second sentence: each hatch is documented in its declaration's JSDoc. */
export function checkHatchDocs(ctx: Context): string[] {
  return ESCAPE_HATCHES.filter((h) => ctx.hatchDocs.get(h) !== true).map(
    (h) =>
      `escape hatch ${h} has no declaration whose JSDoc says "${HATCH_MARK}" in ${HATCH_FILES.join(', ')} (Rule 11.17)`,
  );
}

/** The sub-gap of a typed, raw or planned cell. */
function subGapOf(cell: Cell): SubGap | undefined {
  return cell.status === 'typed' || cell.status === 'raw' || cell.status === 'planned'
    ? cell.subGap
    : undefined;
}

/** A sub-gap names a group of GAP_GROUPS, a note and, when it has one, a positive issue. */
export function checkSubGaps(rows: readonly Row[]): string[] {
  const out: string[] = [];
  for (const row of rows) {
    for (const target of TARGETS) {
      const sub = subGapOf(row[target.key]);
      if (!sub) continue;
      if (!isGroup(sub.group))
        out.push(
          `${where(row, target)} has a sub-gap in group ${sub.group}, which GAP_GROUPS does not define`,
        );
      if (!sub.note.trim()) out.push(`${where(row, target)} has a sub-gap with no note`);
      if (sub.issue !== undefined && !isPositiveInteger(sub.issue)) {
        out.push(
          `${where(row, target)} has a sub-gap naming issue ${sub.issue}, which is not a positive integer`,
        );
      }
    }
  }
  return out;
}

const ISSUE_TOKEN = /(?:^|[\s(;,])#\d+\b|\bissue\s+#\d+/i;
/** The separator of two segments of an evidence string (the evidence grammar, below). */
const SEGMENT_SEPARATOR = '; ';
/** The path that opens a segment: word characters, `@`, `.`, `-` and `/`. */
const SEGMENT_PATH = /^[\w@./-]+/;
/** The line list after a path: `:12`, `:4-9, 15`. */
const LINE_LIST = /^:(\d+(?:-\d+)?(?:, \d+(?:-\d+)?)*)/;
/** One parenthetical comment, after the path or after its line list. */
const COMMENT = /^ \([^()]*\)/;
/** What follows a comment when the writer put the lines after it: `:5`, ` 5`. */
const NUMBER_NEXT = /^:?\s*\d/;

/** The number of lines of each file one `checkEvidence` call cites, read once per call. A file that ends
 *  in a newline has one line less than its newlines split into. */
type LineCounts = Map<string, number>;

function linesOf(root: string, file: string, counts: LineCounts): number {
  const known = counts.get(file);
  if (known !== undefined) return known;
  const text = readFileSync(join(root, file), 'utf8');
  const count = text.endsWith('\n') ? text.split('\n').length - 1 : text.split('\n').length;
  counts.set(file, count);
  return count;
}

/** The messages of one segment of an evidence string (see `checkEvidence`). */
function checkSegment(row: Row, segment: string, ctx: Context, counts: LineCounts): string[] {
  const label = evidenceLabel(row);
  const path = SEGMENT_PATH.exec(segment)?.[0] ?? '';
  if (!path.includes('/') && !path.includes('.')) {
    return [`${label} names no file of the tree: "${segment}"`];
  }
  const refused = pathDefect(path);
  if (refused !== undefined) return [`${label} names ${path}, which ${refused}`];
  let rest = segment.slice(path.length);
  const listed = LINE_LIST.exec(rest);
  if (listed) rest = rest.slice(listed[0].length);
  const comment = COMMENT.exec(rest);
  if (comment) rest = rest.slice(comment[0].length);
  if (rest !== '') {
    if (comment && NUMBER_NEXT.test(rest)) {
      return [
        `${label} has a number after its comment in "${segment}": write the lines after the path`,
      ];
    }
    if (comment)
      return [
        `${label} has text after its comment in "${segment}": nothing may follow the comment`,
      ];
    return [`${label} does not follow the evidence grammar: "${segment}"`];
  }
  const full = join(ctx.root, path);
  if (!existsSync(full)) return [`${label} names ${path}, which does not exist`];
  if (statSync(full).isDirectory())
    return [`${label} names ${path}, which is a directory; cite a file`];
  if (!listed) return [];
  const count = linesOf(ctx.root, path, counts);
  const out: string[] = [];
  for (const part of listed[1]!.split(', ')) {
    const [from, to = from] = part.split('-').map(Number) as [number, number?];
    if (to! < from!) {
      out.push(`${label} cites ${path}:${part}, which runs backwards`);
    } else if (!(from! >= 1 && to! <= count)) {
      out.push(`${label} cites ${path}:${part}, but the file has ${count} lines`);
    }
  }
  return out;
}

/** The evidence of a row follows this grammar (Rule 11.18). The evidence is segments joined by `'; '`.
 *  A segment is a path, then optionally `:` and a line list (`N` or `N-M`, joined by `', '`), then
 *  optionally one parenthetical comment, and nothing after the comment. A number after the comment is
 *  a defect: the lines go after the path. Every line of the list is checked against the file's length,
 *  and a path with no line list names the whole file. An issue is never evidence: it belongs to the
 *  cell. A directory is not a file, so it is not evidence. Node module paths count. A path is
 *  repository-relative: `pathDefect` refuses an absolute path and a `..` segment. A comment cannot
 *  hold `'; '`, because the separator cuts it into two segments: write the comment without it. */
export function checkEvidence(rows: readonly Row[], ctx: Context): string[] {
  const out: string[] = [];
  const counts: LineCounts = new Map();
  for (const row of rows) {
    if (ISSUE_TOKEN.test(row.evidence))
      out.push(`${evidenceLabel(row)} names an issue; an issue belongs to the cell`);
    for (const segment of row.evidence.split(SEGMENT_SEPARATOR)) {
      out.push(...checkSegment(row, segment, ctx, counts));
    }
  }
  return out;
}

/** Every check of the table, in the order `validate()` runs them. */
export const CHECKS: readonly Check[] = [
  { name: 'coverage', run: (rows, sources) => checkCoverage(rows, sources) },
  { name: 'stray', run: (rows, sources) => checkStray(rows, sources) },
  { name: 'hatch-list', run: (_rows, _sources, ctx) => checkHatchList(ctx) },
  { name: 'typed', run: (rows, _sources, ctx) => checkTyped(rows, ctx) },
  { name: 'refused', run: (rows, _sources, ctx) => checkRefused(rows, ctx) },
  { name: 'planned', run: (rows, _sources, ctx) => checkPlanned(rows, ctx) },
  { name: 'raw', run: (rows) => checkRaw(rows) },
  { name: 'gap', run: (rows) => checkGap(rows) },
  { name: 'n/a', run: (rows) => checkNa(rows) },
  { name: 'webgl2-only', run: (rows, _sources, ctx) => checkWebGl2Only(rows, ctx) },
  { name: 'hatch-docs', run: (_rows, _sources, ctx) => checkHatchDocs(ctx) },
  { name: 'sub-gaps', run: (rows) => checkSubGaps(rows) },
  { name: 'evidence', run: (rows, _sources, ctx) => checkEvidence(rows, ctx) },
];

/** Every defect of the table, one message per defect. The test is the gate on them. */
export function validate(
  rows: readonly Row[],
  sources: readonly SourceMember[],
  ctx: Context,
): string[] {
  return CHECKS.flatMap((check) => check.run(rows, sources, ctx));
}

/** The versions the table reads that are not the ones package.json pins (proposal 0059, Unresolved
 *  decisions, item 3). A bake on other versions would write them into the configuration table, so the
 *  bake refuses. One message per version that differs, naming both. */
export function pinMismatches(
  installed: { readonly webgpuTypes: string; readonly typescript: string },
  pinned: { readonly webgpuTypes: string; readonly typescript: string },
): string[] {
  const out: string[] = [];
  if (installed.webgpuTypes !== pinned.webgpuTypes) {
    out.push(
      `@webgpu/types ${installed.webgpuTypes} is installed, and package.json pins ${pinned.webgpuTypes}`,
    );
  }
  if (installed.typescript !== pinned.typescript) {
    out.push(
      `TypeScript ${installed.typescript} is installed, and package.json pins ${pinned.typescript}`,
    );
  }
  return out;
}

// ─── rendering ────────────────────────────────────────────────────────────────────────────────

/** Text outside a code span, on one line: a `<` is written `\<`, so a Markdown renderer shows it and
 *  does not read a tag (`var<immediate>` would otherwise lose the word `immediate`). */
const escText = (text: string): string =>
  text
    .replace(/\s*\n\s*/g, ' ')
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/</g, '\\<')))
    .join('');
/** A table cell: the text of `escText`, and every `|` written `\|`. */
const esc = (text: string): string => escText(text).replace(/\|/g, '\\|');
const issueText = (issue: number | undefined): string => (issue === undefined ? '' : `#${issue}`);

function headOf(cell: Cell): string {
  switch (cell.status) {
    case 'typed':
      return cell.test ? `typed (\`${cell.test}\`)` : 'typed (no test named)';
    case 'raw':
      return `raw (\`${cell.hatch}\`)`;
    case 'refused':
      return `refused (${cell.rule}; portable: ${cell.portable})`;
    case 'planned':
      return `planned (${cell.proposal})`;
    case 'gap':
      return `gap (group ${cell.group}${cell.issue === undefined ? '' : `, ${issueText(cell.issue)}`})`;
    case 'n/a':
      return `n/a (${cell.reason})`;
  }
}

/** One cell as the table shows it: the status, the note, and the sub-gap inside it. */
export function cellText(cell: Cell): string {
  const parts = [headOf(cell)];
  const note = cell.status === 'n/a' ? undefined : cell.note;
  if (note) parts.push(note);
  const sub = subGapOf(cell);
  if (sub) {
    const issue = sub.issue === undefined ? '' : ` (${issueText(sub.issue)})`;
    parts.push(`gap inside: group ${sub.group}${issue}: ${sub.note}`);
  }
  return parts.join('; ');
}

function doorText(door: Door): string {
  switch (door.door) {
    case '§9.3':
      return `§9.3 row \`${door.row}\``;
    case '§10':
      return `§10 capability \`${door.capability}\``;
    case 'none':
      return 'none yet (Rule 11.16)';
  }
}

interface Counts {
  readonly rows: number;
  readonly typed: number;
  readonly raw: number;
  readonly refused: number;
  readonly planned: number;
  readonly gap: number;
  readonly 'n/a': number;
}

/** The status counts of one target over the given rows. */
export function countOf(rows: readonly Row[], target: Target): Counts {
  const out: Record<Status | 'rows', number> = {
    rows: rows.length,
    typed: 0,
    raw: 0,
    refused: 0,
    planned: 0,
    gap: 0,
    'n/a': 0,
  };
  for (const row of rows) out[row[target.key].status] += 1;
  return out;
}

function table(headers: readonly string[], body: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]): string => `| ${cells.join(' | ')} |`;
  return [line(headers), line(headers.map(() => '---')), ...body.map(line)].join('\n');
}

const countCells = (c: Counts): string[] =>
  [...STATUSES, 'rows' as const].map((k) => String(k === 'rows' ? c.rows : c[k]));

function countsTable(rows: readonly Row[], withTable: boolean): string {
  const body: string[][] = [];
  const headers = withTable
    ? ['Table', 'Target', ...STATUSES, 'rows']
    : ['Target', ...STATUSES, 'rows'];
  for (const t of TABLES) {
    const inTable = rows.filter((r) => r.table === t);
    for (const target of TARGETS) {
      const c = countOf(inTable, target);
      body.push(withTable ? [t, target.label, ...countCells(c)] : [target.label, ...countCells(c)]);
    }
  }
  for (const target of TARGETS) {
    const c = countOf(rows, target);
    body.push(
      withTable ? ['all', target.label, ...countCells(c)] : [target.label, ...countCells(c)],
    );
  }
  return table(headers, body);
}

