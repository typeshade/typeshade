import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import ts from 'typescript';

export const BASELINE_PATH = 'scripts/comment-baseline.json';

const MARKER =
  /Verifies:|LINT\.(?:IfChange|ThenChange)|eslint-disable|@ts-(?:ignore|expect-error|nocheck)|@vitest-environment|^#!|SPDX-License-Identifier|Copyright/;

const GENERATED = /GENERATED FILE|Generated by |@generated/;

export function publicDefinitions(surface: string): Set<string> {
  const keys = new Set<string>();
  for (const line of surface.split('\n')) {
    const match = /^(src\/\S+)#([A-Za-z_$][\w$]*)/.exec(line);
    if (match) keys.add(`${match[1]}#${match[2]}`);
  }
  return keys;
}

function declaredNames(node: ts.Node): string[] {
  if (ts.isVariableStatement(node)) {
    return node.declarationList.declarations
      .map((d) => d.name)
      .filter(ts.isIdentifier)
      .map((n) => n.text);
  }
  const name = (node as ts.NamedDeclaration).name;
  return name && ts.isIdentifier(name) ? [name.text] : [];
}

export function bannedCommentLines(path: string, text: string, publicKeys: Set<string>): number {
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
  const allowed = new Set<number>();
  const visit = (node: ts.Node, isPublic: boolean): void => {
    const here =
      (isPublic && !ts.isBlock(node)) ||
      (node.parent === source && declaredNames(node).some((n) => publicKeys.has(`${path}#${n}`)));
    if (here) {
      for (const doc of ts.getJSDocCommentsAndTags(node)) {
        if (ts.isJSDoc(doc)) allowed.add(doc.pos);
      }
    }
    ts.forEachChild(node, (child) => visit(child, here));
  };
  visit(source, false);

  const seen = new Set<number>();
  let banned = 0;
  const count = (ranges: readonly ts.CommentRange[] | undefined): void => {
    for (const range of ranges ?? []) {
      if (seen.has(range.pos)) continue;
      seen.add(range.pos);
      const body = text.slice(range.pos, range.end);
      if (allowed.has(range.pos) || MARKER.test(body)) continue;
      banned += body.split('\n').length;
    }
  };
  const scan = (node: ts.Node): void => {
    count(ts.getLeadingCommentRanges(text, node.getFullStart()));
    count(ts.getTrailingCommentRanges(text, node.getEnd()));
    ts.forEachChild(node, scan);
  };
  scan(source);
  return banned;
}

export function policedFiles(root: string): string[] {
  return execFileSync('git', ['ls-files', '-z', '--', 'src'], { cwd: root, encoding: 'utf8' })
    .split('\0')
    .filter((path) => path.endsWith('.ts') && !path.endsWith('.shade.ts'))
    .filter((path) => !GENERATED.test(readFileSync(join(root, path), 'utf8').slice(0, 600)))
    .sort();
}

export function countComments(root: string): Record<string, number> {
  const publicKeys = publicDefinitions(readFileSync(join(root, 'src/__api__/surface.md'), 'utf8'));
  const counts: Record<string, number> = {};
  for (const path of policedFiles(root)) {
    const lines = bannedCommentLines(path, readFileSync(join(root, path), 'utf8'), publicKeys);
    if (lines > 0) counts[path] = lines;
  }
  return counts;
}

export function readBaseline(root: string): Record<string, number> {
  return JSON.parse(readFileSync(join(root, BASELINE_PATH), 'utf8')) as Record<string, number>;
}
